import assert from "node:assert/strict"
import fs from "node:fs"
import os from "node:os"
import path from "node:path"
import {spawnSync} from "node:child_process"
const tmp=fs.mkdtempSync(path.join(os.tmpdir(),"shared-clients-"))
try {
 const home=path.join(tmp,"home"),repo=path.join(tmp,"project")
 fs.mkdirSync(repo,{recursive:true})
 const selected=await (await import("./test-home.mjs")).configureTestHome(home)
 fs.mkdirSync(path.dirname(selected.file),{recursive:true})
 fs.writeFileSync(selected.file,JSON.stringify({project_settings:[{project:"sample",root:repo}]}))
 fs.mkdirSync(path.join(repo,".canopus/plugin"),{recursive:true});fs.writeFileSync(path.join(repo,".canopus/plugin/config.json"),JSON.stringify({tasks_dir:"docs/tasks"}))
 const packageRoot=path.join(tmp,"package")
 for(const file of ["scripts/task-store.mjs","opencode-plugin/shared-task-store.ts","opencode-plugin/shared-task-config.ts","opencode-plugin/shared-task-snapshot.ts","opencode-plugin/task-numbers.ts"]){
  const dest=path.join(packageRoot,file);fs.mkdirSync(path.dirname(dest),{recursive:true});fs.copyFileSync(path.resolve(import.meta.dirname,"../..",file),dest)
 }
 const cli=path.join(packageRoot,"scripts/task-store.mjs")
 const run=(action,input)=>spawnSync(process.execPath,[cli,action,"--config",selected.file,"--root",repo,"--json",JSON.stringify(input??{})],{encoding:"utf8",windowsHide:true})
 const attempted=run("create",{ownerConfirmed:true,session:"s",title:"forged"})
 assert.notEqual(attempted.status,0,"Boolean owner assertions cannot create tasks")
 const reservation=run("reserve",{title:"Shared task"});assert.equal(reservation.status,0,reservation.stderr)
 const r=JSON.parse(reservation.stdout)
 assert.equal(fs.existsSync(r.file),false,"Reservation is not a task")
 const evidence=path.join(home,"state/task-events/s.json");fs.mkdirSync(path.dirname(evidence),{recursive:true})
 fs.writeFileSync(evidence,JSON.stringify({session:"s",name:"route_task",text:JSON.stringify({op:"open",number:String(r.n),dir:r.dir,title:"Shared task"}),step:1}))
 const accepted=run("record-event",{session:"s",evidence,n:r.n});assert.equal(accepted.status,0,accepted.stderr)
 const tasks=await import("../tasks.ts");const t=tasks.loadTask("sample",r.n)
 assert.equal(t.history[0].status,"running");assert.equal(t.title,"Shared task");assert.equal(t.application.events.length,1)
 const replay=run("record-event",{session:"s",evidence,n:r.n});assert.equal(replay.status,0,replay.stderr)
 assert.equal(tasks.loadTask("sample",r.n).application.events.length,1,"Persistence is idempotent and does not replay actions")
 const acceptedEvidence=fs.readFileSync(evidence)
 fs.writeFileSync(evidence,JSON.stringify({session:"s",name:"route_note",text:"not persisted yet",step:2}))
 assert.match(JSON.parse(run("read",{n:r.n}).stdout).execution_block,/persistence is pending/)
 assert.notEqual(run("snapshot",{session:"s",n:r.n}).status,0,"Unpersisted events cannot be published")
 fs.writeFileSync(evidence,JSON.stringify({session:"s",name:"route_task",text:JSON.stringify({op:"open",number:String(r.n+1),dir:r.dir,title:"wrong task"}),step:2}))
 assert.notEqual(run("record-event",{session:"s",evidence,n:r.n}).status,0,"A later task cannot overwrite an earlier task of the same session")
 fs.writeFileSync(evidence,acceptedEvidence)
 t.status="paused";tasks.saveTask(t)
 const appRead=run("read",{n:r.n});assert.equal(appRead.status,0,appRead.stderr);assert.equal(JSON.parse(appRead.stdout).status,"paused")
 assert.notEqual(run("snapshot",{session:"s",n:r.n}).status,0,"Paused tasks cannot publish")
 fs.writeFileSync(path.join(path.dirname(r.file),"watch.json"),JSON.stringify({project:"sample",n:r.n,hold:{scope:"execution",reason:"owner STOP"}}))
 assert.equal(JSON.parse(run("read",{n:r.n}).stdout).execution_block,"execution HOLD/STOP")
 assert.equal(run("record-event",{session:"foreign",evidence,n:r.n}).status,1)
 assert.equal(tasks.loadTask("sample",r.n).status,"paused")
 assert.equal(tasks.taskFile("sample",r.n),r.file)
 const catalogFile=path.join(home,"state/task-projects.json")
 const catalog=JSON.parse(fs.readFileSync(catalogFile,"utf8"));fs.writeFileSync(catalogFile,JSON.stringify({...catalog,legacy:repo}))
 assert.equal(tasks.taskFile("legacy",r.n),r.file,"Historic project identifiers resolve to the same canonical record")
 assert.equal(tasks.listTasks().filter(t=>t.n===r.n).length,1,"Aliases do not duplicate shared records")
 fs.writeFileSync(evidence,JSON.stringify({session:"s",name:"route_task",text:JSON.stringify({op:"state",state:"active"}),step:3}))
 assert.equal(run("record-event",{session:"s",evidence,n:r.n}).status,0)
 assert.equal(tasks.loadTask("sample",r.n).status,"paused","Application cache cannot implicitly resume a paused task")
 assert.throws(()=>tasks.saveTask(t),/changed/,"Stale plugin state cannot overwrite later application events")
 fs.writeFileSync(evidence,JSON.stringify({session:"s",name:"route_task",text:JSON.stringify({op:"attach_tree",branch:"task/fixture",worktree:path.join(tmp,"tree")}),step:4}))
 assert.equal(run("record-event",{session:"s",evidence,n:r.n}).status,0)
 assert.equal(tasks.loadTask("sample",r.n).branch,"task/fixture")
 fs.writeFileSync(evidence,JSON.stringify({session:"s",name:"route_task",text:JSON.stringify({op:"new"}),step:5}))
 assert.equal(run("record-event",{session:"s",evidence,n:r.n}).status,0)
 assert.equal(tasks.loadTask("sample",r.n).status,"done","Closing the previous task preserves its identity and completes its shared record")
 const finished=fs.readFileSync(r.file)
 assert.equal(run("record-event",{session:"s",evidence,n:r.n}).status,0)
 assert.deepEqual(fs.readFileSync(r.file),finished,"Repeated close evidence is inert")

 console.log("Shared clients: one record, owner flag refused, reservation inert, plugin pause visible, duplicate event inert, foreign session refused: green")
} finally {fs.rmSync(tmp,{recursive:true,force:true})}
