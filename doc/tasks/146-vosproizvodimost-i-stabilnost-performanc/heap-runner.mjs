// Task 146 isolated diagnostic runner. Requires a separately reviewed frozen manifest.
import assert from "node:assert/strict"
import { createHash } from "node:crypto"
import { spawnSync } from "node:child_process"
import { existsSync, lstatSync, readFileSync, readdirSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { gate, heapFlags, schedule, statistics } from "./heap-observation.mjs"

const hash = (bytes) => createHash("sha256").update(bytes).digest("hex")
const same = (a, b) => assert.deepEqual(a, b)
export function validateRecord(record, mode, processIndex, exitCode) {
  same(record.mode, mode)
  same(record.processIndex, processIndex)
  same(record.node, "v24.15.0")
  same(record.v8, "13.6.233.17-node.48")
  same(record.execArgv, mode === "C" ? [] : heapFlags)
  same(record.crewEnvKeys, [])
  assert(record.attempts.length >= 1 && record.attempts.length <= 3)
  for (const [index, a] of record.attempts.entries()) {
    same(a.attempt, index + 1)
    same(a.c, statistics(a.coldMs))
    same(a.r, statistics(a.readMs))
    same(a.ok, gate(a.c, a.r))
    if (index < record.attempts.length - 1) same(a.ok, false)
    same(a.intervals.length, 40)
    for (const [i, sample] of a.intervals.entries()) {
      same(sample.kind, i % 2 ? "read" : "cold")
      same(sample.index, Math.floor(i / 2))
      assert(Number.isFinite(sample.startMs) && Number.isFinite(sample.endMs) && sample.startMs <= sample.endMs)
      if (i) assert(sample.startMs >= a.intervals[i - 1].endMs)
      same(sample.endMs - sample.startMs, (i % 2 ? a.readMs : a.coldMs)[Math.floor(i / 2)])
    }
    for (const snapshot of [a.heapBefore, a.heapAfter]) {
      assert(Array.isArray(snapshot) && snapshot.some((s) => s.space_name === "new_space"))
      if (mode !== "C") assert(snapshot.find((s) => s.space_name === "new_space").space_size >= 64 * 1024 * 1024)
    }
  }
  const last = record.attempts.at(-1)
  same(record.result, { c: last.c, r: last.r, ok: last.ok })
  if (!last.ok) same(record.attempts.length, 3)
  same(exitCode, last.ok ? 0 : 1)
  assert(Array.isArray(record.gcEvents))
  for (const e of record.gcEvents) assert(Number.isFinite(e.startMs) && Number.isFinite(e.durationMs) && e.durationMs >= 0 && Number.isInteger(e.kind))
  return true
}

function snapshot(root, rel = "") {
  return readdirSync(path.join(root, rel)).sort().flatMap((name) => {
    const file = path.join(rel, name)
    const stat = lstatSync(path.join(root, file))
    assert(!stat.isSymbolicLink(), "symlink in isolated root")
    if (stat.isDirectory()) return snapshot(root, file)
    assert(stat.isFile(), "non-file in isolated root")
    return [{ file: file.replaceAll("\\", "/"), sha256: hash(readFileSync(path.join(root, file))) }]
  })
}

function run(manifestFile, receiptFile) {
  // A review receipt is a separate explicit input, never generated by this runner.
  const manifestBytes = readFileSync(manifestFile)
  const manifest = JSON.parse(manifestBytes)
  const receipt = JSON.parse(readFileSync(receiptFile, "utf8"))
  same(receipt.manifestSha256, hash(manifestBytes))
  same(receipt.runnerSha256, hash(readFileSync(fileURLToPath(import.meta.url))))
  same(receipt.observationSha256, hash(readFileSync(new URL("./heap-observation.mjs", import.meta.url))))
  same(receipt.authorized, true)
  same(manifest.schedule, schedule)
  same(manifest.nodeExeSha256, hash(readFileSync(process.execPath)))
  const base = path.dirname(path.resolve(manifestFile))
  for (let i = 1; i <= schedule.length; i++) {
    for (const suffix of ["stdout.txt", "stderr.txt", "record.json"]) {
      assert(!existsSync(path.join(base, `heap-child-${String(i).padStart(2, "0")}.${suffix}`)), "previous block output exists; do not rerun")
    }
  }
  const roots = Object.fromEntries(["C", "H", "D"].map((arm) => [arm, path.resolve(base, manifest.arms[arm].root)]))
  assert(new Set(Object.values(roots)).size === 3, "roots must be independent")
  const check = () => {
    for (const arm of ["C", "H", "D"]) same(snapshot(roots[arm]), manifest.arms[arm].files)
  }
  check()
  let firstFailures = { C: 0, H: 0, D: 0 }
  const processFailures = { C: 0, H: 0, D: 0 }
  for (const [index, arm] of schedule.entries()) {
    check()
    const env = Object.fromEntries(Object.entries(process.env).filter(([k]) => !/^(CREW_|PERF_|NODE_OPTIONS$)/i.test(k)))
    env.PERF_MODE = arm
    env.PERF_PROCESS_INDEX = String(index + 1)
    const args = [...(arm === "C" ? [] : heapFlags), manifest.arms[arm].entry]
    const child = spawnSync(process.execPath, args, { cwd: roots[arm], env, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 })
    const output = path.join(base, `heap-child-${String(index + 1).padStart(2, "0")}`)
    // Exclusive writes prevent accidental replacement of a previous block.
    writeFileSync(`${output}.stdout.txt`, child.stdout ?? "", { flag: "wx" })
    writeFileSync(`${output}.stderr.txt`, child.stderr ?? "", { flag: "wx" })
    assert(!child.error && child.signal === null, "child launch/signal failure")
    const lines = child.stdout.split(/\r?\n/)
    const records = lines.filter((l) => l.startsWith("HEAP_PROBE "))
    same(records.length, 1)
    const record = JSON.parse(records[0].slice("HEAP_PROBE ".length))
    validateRecord(record, arm, index + 1, child.status)
    const failures = lines.filter((l) => l.startsWith("FAIL"))
    same(failures.length, record.result.ok ? 0 : 1)
    if (failures.length) assert(failures[0].startsWith("FAIL AC-11 б "), "non-target assertion failure")
    same(child.stderr, "")
    // Actual resolved import hashes and both runtime fixture snapshots are mandatory.
    same(record.imports, manifest.arms[arm].imports)
    same(record.fixtureBefore, manifest.fixture)
    same(record.fixtureAfter, manifest.fixture)
    if (arm === "D") assert(Number.isInteger(record.slowChecksum) && record.slowChecksum > 0, "missing slow-work sink")
    check()
    if (!record.attempts[0].ok) firstFailures[arm]++
    if (!record.result.ok) processFailures[arm]++
    writeFileSync(`${output}.record.json`, JSON.stringify(record) + "\n", { flag: "wx" })
    console.log(JSON.stringify({ process: index + 1, arm, exitCode: child.status, firstPassed: record.attempts[0].ok, attempts: record.attempts.length }))
  }
  const negativeControlConfirmed = processFailures.D === 10
  console.log(JSON.stringify({ completed: 30, firstFailures, processFailures, negativeControlConfirmed, note: "diagnostic only, not a post-fix gate" }))
  if (!negativeControlConfirmed) process.exitCode = 1
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  assert(process.argv.length === 5 && process.argv[2] === "--run", "usage: node heap-runner.mjs --run frozen-manifest.json review-receipt.json")
  run(process.argv[3], process.argv[4])
}
